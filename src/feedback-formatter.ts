import { ReviewState, Issue } from './code-review-agent';

export class FeedbackFormatter {
  static formatAsMarkdown(state: ReviewState): string {
    if (state.allIssues.length === 0) {
      return this.formatNoIssues();
    }

    let feedback = this.formatHeader();

    // Group by severity
    const bySeverity = this.groupBySeverity(state.allIssues);

    // Critical issues
    if (bySeverity.critical.length > 0) {
      feedback += this.formatCriticalSection(bySeverity.critical);
    }

    // High severity issues
    if (bySeverity.high.length > 0) {
      feedback += this.formatHighSection(bySeverity.high);
    }

    // Medium severity issues
    if (bySeverity.medium.length > 0) {
      feedback += this.formatMediumSection(bySeverity.medium);
    }

    // Low severity issues
    if (bySeverity.low.length > 0) {
      feedback += this.formatLowSection(bySeverity.low);
    }

    feedback += this.formatSummary(bySeverity);

    return feedback;
  }

  private static formatHeader(): string {
    return '# 🔍 Code Review Report\n\n' +
           'Generated by Agentic Code Reviewer\n\n';
  }

  private static formatNoIssues(): string {
    return '# ✅ Code Review Complete\n\n' +
           'No issues detected! Excellent code quality.\n';
  }

  private static groupBySeverity(issues: Issue[]) {
    return {
      critical: issues.filter(i => i.severity === 'critical'),
      high: issues.filter(i => i.severity === 'high'),
      medium: issues.filter(i => i.severity === 'medium'),
      low: issues.filter(i => i.severity === 'low'),
    };
  }

  private static formatCriticalSection(issues: Issue[]): string {
    let section = '## 🚨 Critical Issues\n\n';
    const displayed = issues.slice(0, 5);
    for (const issue of displayed) {
      section += this.formatIssueItem(issue);
    }
    if (issues.length > 5) {
      section += `\n_... and ${issues.length - 5} more critical issues_\n\n`;
    }
    return section;
  }

  private static formatHighSection(issues: Issue[]): string {
    let section = '## ⚠️ High Priority Issues\n\n';
    const displayed = issues.slice(0, 5);
    for (const issue of displayed) {
      section += this.formatIssueItem(issue);
    }
    if (issues.length > 5) {
      section += `\n_... and ${issues.length - 5} more high priority issues_\n\n`;
    }
    return section;
  }

  private static formatMediumSection(issues: Issue[]): string {
    let section = '## ℹ️ Medium Priority Issues\n\n';
    const displayed = issues.slice(0, 3);
    for (const issue of displayed) {
      section += this.formatIssueItem(issue);
    }
    if (issues.length > 3) {
      section += `\n_... and ${issues.length - 3} more medium priority issues_\n\n`;
    }
    return section;
  }

  private static formatLowSection(issues: Issue[]): string {
    let section = '## 📌 Low Priority Issues\n\n';
    const displayed = issues.slice(0, 3);
    for (const issue of displayed) {
      section += this.formatIssueItem(issue);
    }
    if (issues.length > 3) {
      section += `\n_... and ${issues.length - 3} more low priority issues_\n\n`;
    }
    return section;
  }

  private static formatIssueItem(issue: Issue): string {
    let item = `### ${issue.type}\n`;
    item += `- **File:** ${issue.filename || 'N/A'}\n`;
    item += `- **Line:** ${issue.lineNumber || 'N/A'}\n`;
    item += `- **Issue:** ${issue.message}\n`;
    item += `- **Suggestion:** ${issue.suggestion}\n\n`;
    return item;
  }

  private static formatSummary(bySeverity: any): string {
    const total = Object.values(bySeverity)
      .reduce((sum: number, arr: any) => sum + arr.length, 0);

    return '---\n\n' +
           '## Summary\n\n' +
           `**Total Issues Found:** ${total}\n\n` +
           `- 🚨 Critical: ${bySeverity.critical.length}\n` +
           `- ⚠️ High: ${bySeverity.high.length}\n` +
           `- ℹ️ Medium: ${bySeverity.medium.length}\n` +
           `- 📌 Low: ${bySeverity.low.length}\n`;
  }
}

export default FeedbackFormatter;
